/**
 * Tipos de dados e concatenação
 * 
 * sinal de + pode ser usado para somar numeros ou concatenar strings
 * o acento crase (`) pode ser usado para concatenar strings e interpolar valores
 */

const nome = "João";
const idade = 25;
const altura = 1.75;

console.log("Nome: " + nome);
console.log("Idade: " + idade);
console.log("Altura: " + altura);

console.log(`Nome: ${nome}`);
console.log(`Idade: ${idade}`);
console.log(`Altura: ${altura}`);
